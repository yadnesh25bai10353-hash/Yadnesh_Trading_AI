    if not line:
        continue
    if line.startswith("2026-"):
        # Format date as 'Jul 27'
        parts = line.split('-')
        months = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]
